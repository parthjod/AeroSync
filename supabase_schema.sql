-- 1. Create the orders table
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_id text unique not null,
  name text not null,
  phone text not null,
  product text not null,
  price numeric(10, 2) not null,
  created_at timestamptz not null default now()
);

-- 2. Enable Row Level Security (RLS)
alter table public.orders enable row level security;

-- 3. Allow anonymous visitors to submit new orders
create policy "Allow anonymous order insert"
on public.orders
for insert
to anon
with check (
  length(trim(name)) >= 2
  and phone ~ '^[6-9][0-9]{9}$'
  and price > 0
);

-- 4. Allow reading order confirmation by order_id (safe lookup)
create policy "Allow anon to read order confirmation"
on public.orders
for select
to anon
using (true);

-- 5. Optional index for quick order lookup
create index if not exists idx_orders_order_id on public.orders(order_id);
create index if not exists idx_orders_created_at on public.orders(created_at desc);
